#!/usr/bin/env node
/**
 * build-media-manifest.mjs — record what media exists, for a build that cannot look.
 *
 * ### Why this exists
 *
 * The data layer used to enumerate media with `import.meta.glob`, i.e. a DISK SCAN at
 * build time. That works only because the media is committed and therefore present on
 * the CI runner. The moment media moves to object storage, the glob returns `{}` on the
 * runner — not an error, just nothing — and the site builds green with empty galleries.
 *
 * So the answer is computed on the machine that HAS the media, written here, and
 * committed. The build reads this file and never touches the disk.
 *
 * ### THIS MANIFEST REBUILDS. IT DOES NOT MERGE.
 *
 * It scans the media root and writes the result wholesale. Run it anywhere the full
 * media tree is NOT present and it will happily record a near-empty tree and wipe every
 * other entry.
 *
 *   - Safe:   your laptop, with all the media.
 *   - UNSAFE: any CI runner, which holds only what it just encoded.
 *
 * CI must set SKIP_REBUILD_MANIFESTS=1. There is a second belt in the workflow:
 * `git checkout -- src/data/media-manifest.json` after any pipeline step.
 *
 * ### Usage
 *
 *   node tools/pipeline/build-media-manifest.mjs             # write it
 *   node tools/pipeline/build-media-manifest.mjs --check     # verify it matches disk (needs the media)
 *   node tools/pipeline/build-media-manifest.mjs --validate  # structural check only (safe in CI)
 *
 * ### Why --validate exists, and why it gates the build
 *
 * `src/lib/mediaManifest.js` throws on an empty manifest, but that throw runs in
 * the BROWSER, when the module is imported — not when Vite bundles it. A sabotage
 * test on 2026-08-09 emptied the manifest and the build went GREEN, with the
 * failure deferred to runtime. That is the precise failure this whole manifest
 * exists to prevent, reintroduced one layer up.
 *
 * So `--validate` runs as npm's `prebuild` and fails the build itself. It reads
 * ONLY the manifest — no disk scan — so it is safe on a media-less runner, which
 * `--check` is not.
 */
import { readdir, writeFile, readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../..', import.meta.url));
const MEDIA_ROOT = process.env.MEDIA_ROOT || join(ROOT, 'public', 'projects');
const ABOUT_ROOT = process.env.ABOUT_ROOT || join(ROOT, 'public', 'about');
const OUT = join(ROOT, 'src', 'data', 'media-manifest.json');

// Mirrors the extensions the old globs accepted. Anything outside this set was
// invisible to the site before and stays invisible now — but it gets REPORTED
// rather than silently dropped, because a silently ignored file looks exactly
// like a missing one when a gallery comes up short.
const GALLERY_EXT = /\.(jpg|jpeg|png|webp|gif|mp4|webm)$/i;
const COMPARE_EXT = /\.(jpg|jpeg|png|webp|mp4|webm)$/i;
const ABOUT_EXT = /\.(jpg|jpeg|png|webp)$/i;
const HERO_RE = /^hero\.(mp4|webm)$/i;

async function dirNames(dir) {
  if (!existsSync(dir)) return [];
  const entries = await readdir(dir, { withFileTypes: true });
  return entries.filter((e) => e.isDirectory() && !e.name.startsWith('.')).map((e) => e.name);
}

async function fileNames(dir) {
  if (!existsSync(dir)) return [];
  const entries = await readdir(dir, { withFileTypes: true });
  return entries.filter((e) => e.isFile() && !e.name.startsWith('.')).map((e) => e.name);
}

async function build() {
  const skipped = [];
  const projects = {};

  for (const slug of (await dirNames(MEDIA_ROOT)).sort()) {
    const slugDir = join(MEDIA_ROOT, slug);
    const all = await fileNames(slugDir);

    for (const f of all) {
      if (!GALLERY_EXT.test(f)) skipped.push(`${slug}/${f}`);
    }

    // `hero.mp4` / `hero.webm` is reserved for the page hero and is deliberately
    // NOT part of the gallery, so the project page never shows it twice.
    const hero = all.find((f) => HERO_RE.test(f)) || null;
    const files = all
      .filter((f) => GALLERY_EXT.test(f) && !HERO_RE.test(f))
      .sort((a, b) => a.localeCompare(b));

    const compareDir = join(slugDir, 'compare');
    const compare = (await fileNames(compareDir))
      .filter((f) => COMPARE_EXT.test(f))
      .sort((a, b) => a.localeCompare(b));

    if (!files.length && !hero && !compare.length) continue;
    projects[slug] = { files, ...(hero ? { hero } : {}), ...(compare.length ? { compare } : {}) };
  }

  const about = (await fileNames(ABOUT_ROOT)).filter((f) => ABOUT_EXT.test(f)).sort();

  return {
    manifest: {
      kind: 'rebuilding',
      note: 'Generated by tools/pipeline/build-media-manifest.mjs. Do not edit by hand. REBUILDS from a disk scan — never regenerate where the full media tree is absent (CI: SKIP_REBUILD_MANIFESTS=1).',
      generated: new Date().toISOString(),
      projects,
      about,
    },
    skipped,
  };
}

// Compare ignoring `generated`, so a no-op run is not reported as drift.
const comparable = (m) => JSON.stringify({ projects: m.projects, about: m.about });

/**
 * Structural validation of the COMMITTED manifest. Reads no media, so it is the
 * only variant safe to run where the media tree is absent — which is exactly
 * where an empty manifest would otherwise sail through.
 */
async function validate() {
  if (!existsSync(OUT)) {
    console.error('[media-manifest] --validate: src/data/media-manifest.json does not exist.');
    console.error('[media-manifest] the build cannot enumerate media without it.');
    console.error('[media-manifest] regenerate on a machine with the media: npm run media:manifest');
    process.exit(1);
  }

  let m;
  try {
    m = JSON.parse(await readFile(OUT, 'utf8'));
  } catch (err) {
    console.error(`[media-manifest] --validate: manifest is not valid JSON — ${err.message}`);
    process.exit(1);
  }

  if (!m.projects || typeof m.projects !== 'object') {
    console.error('[media-manifest] --validate: manifest has no `projects` object.');
    process.exit(1);
  }

  const slugs = Object.keys(m.projects);
  if (slugs.length === 0) {
    console.error('[media-manifest] --validate: manifest contains ZERO projects.');
    console.error('[media-manifest] Shipping this is a green build with every gallery empty.');
    console.error('[media-manifest] Almost always caused by regenerating where the media was absent.');
    console.error('[media-manifest] Fix: git checkout -- src/data/media-manifest.json');
    process.exit(1);
  }

  const empty = slugs.filter((s) => {
    const p = m.projects[s];
    return !(p.files?.length || p.hero || p.compare?.length);
  });
  if (empty.length) {
    console.error(`[media-manifest] --validate: ${empty.length} project(s) have no media at all: ${empty.join(', ')}`);
    process.exit(1);
  }

  const fileCount = slugs.reduce(
    (n, s) => n + m.projects[s].files.length
      + (m.projects[s].hero ? 1 : 0)
      + (m.projects[s].compare?.length ?? 0), 0);
  console.log(`[media-manifest] --validate: OK — ${slugs.length} projects, ${fileCount} files.`);
}

async function main() {
  const check = process.argv.includes('--check');

  if (process.argv.includes('--validate')) {
    await validate();
    return;
  }

  if (!existsSync(MEDIA_ROOT)) {
    console.error(`[media-manifest] media root not found: ${MEDIA_ROOT}`);
    console.error('[media-manifest] refusing to write a manifest from a tree that is not there.');
    console.error('[media-manifest] this is the REBUILD hazard: writing now would erase every entry.');
    process.exit(1);
  }

  const { manifest, skipped } = await build();
  const slugs = Object.keys(manifest.projects);
  const fileCount = slugs.reduce(
    (n, s) => n + manifest.projects[s].files.length
      + (manifest.projects[s].hero ? 1 : 0)
      + (manifest.projects[s].compare?.length ?? 0), 0);

  // A scan that finds nothing is far more likely to be a wrong path than a real
  // empty tree, and writing it would wipe the committed manifest. Fail safe.
  if (slugs.length === 0) {
    console.error(`[media-manifest] scanned ${MEDIA_ROOT} and found NO projects.`);
    console.error('[media-manifest] refusing to write an empty manifest.');
    process.exit(1);
  }

  if (skipped.length) {
    console.warn(`[media-manifest] ${skipped.length} file(s) ignored (unsupported extension):`);
    for (const s of skipped.slice(0, 10)) console.warn(`  - ${s}`);
    if (skipped.length > 10) console.warn(`  … and ${skipped.length - 10} more`);
  }

  if (check) {
    if (!existsSync(OUT)) {
      console.error('[media-manifest] --check: manifest does not exist.');
      process.exit(1);
    }
    const onDisk = JSON.parse(await readFile(OUT, 'utf8'));
    if (comparable(onDisk) !== comparable(manifest)) {
      console.error('[media-manifest] --check: manifest is STALE — it does not match the media on disk.');
      console.error('[media-manifest] regenerate with: node tools/pipeline/build-media-manifest.mjs');
      process.exit(1);
    }
    console.log(`[media-manifest] --check: up to date (${slugs.length} projects, ${fileCount} files).`);
    return;
  }

  await writeFile(OUT, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
  console.log(`[media-manifest] wrote src/data/media-manifest.json`);
  console.log(`[media-manifest] ${slugs.length} projects, ${fileCount} files, ${manifest.about.length} about image(s)`);
}

main().catch((err) => {
  console.error(`[media-manifest] ${err.message}`);
  process.exit(1);
});
